"""Conservative region check for an outfit candidate; never grants approval."""
from pathlib import Path

from PIL import Image

from .pipeline import load, structure


def load_editable_mask(spec: dict, sheet: Image.Image, editable_mask: Path) -> Image.Image:
    """Load source-authorized binary edit regions without expanding them."""
    with Image.open(editable_mask) as image:
        if image.format != "PNG" or image.mode != "L" or getattr(image, "n_frames", 1) != 1:
            raise ValueError("editable mask must be a static grayscale PNG")
        mask = image.copy()
    if mask.size != sheet.size or not set(mask.get_flattened_data()) <= {0, 255}:
        raise ValueError("editable mask must match source sheet dimensions and contain only 0/255")
    occupied = Image.new("L", sheet.size)
    for entry in spec["frames"]:
        x, y, w, h = entry["rect"]
        occupied.paste(255, (x, y, x + w, y + h))
        region = mask.crop((x, y, x + w, y + h))
        if region.getextrema() != (0, 255):
            raise ValueError("every frame needs both permitted and protected pixels")
    if any(m and not f for m, f in zip(mask.get_flattened_data(), occupied.get_flattened_data())):
        raise ValueError("editable mask permits changes outside declared frames")
    return mask


def validate_outfit(source: Path, candidate: Path, editable_mask: Path) -> dict:
    """Allow clothing edits inside a binary mask; protect everything else exactly.

    The mask is authored against the source sheet, not generated by the provider.
    This checks pixels/metadata, not semantic pose, clothing or provider success.
    """
    before, original, source_frames = load(source)
    after, output, target_frames = load(candidate)
    mask = load_editable_mask(before, original, editable_mask)
    errors = []
    if structure(before) != structure(after):
        errors.append("animation metadata changed (ids, order, rects, timing, anchors or loop)")
    if original.size != output.size:
        errors.append("sheet dimensions changed")
    changed = 0
    protected_changed = False
    if original.size == output.size:
        for p, q, allowed in zip(original.get_flattened_data(), output.get_flattened_data(), mask.get_flattened_data()):
            if p != q:
                changed += 1
                if not allowed:
                    protected_changed = True
        if protected_changed:
            errors.append("pixels changed outside permitted clothing regions")
    source_pixels = {frame.tobytes() for frame in source_frames}
    seen = set()
    for index, frame in enumerate(target_frames):
        pixels = frame.tobytes()
        if pixels in source_pixels:
            errors.append(f"frame {index}: unchanged or substituted source frame")
        if pixels in seen:
            errors.append(f"frame {index}: duplicate candidate frame")
        seen.add(pixels)
    return {"ok": not errors, "profile": "outfit-regions-v1", "errors": errors,
            "frame_count": len(target_frames), "changed_pixels": changed,
            "approved": False, "review_status": "pending" if not errors else "blocked",
            "review_required": ["pose and movement", "outfit and identity consistency",
                                "genuine garment change", "provider success and provenance"]}
